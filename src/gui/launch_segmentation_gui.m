function onBrowseImage(fig)
    state = getappdata(fig, 'AppState');
    startDir = fullfile(state.projectRoot, 'data');
    if exist(startDir, 'dir') ~= 7
        startDir = state.projectRoot;
    end

    [fn, fp] = uigetfile( ...
        {'*.png;*.jpg;*.jpeg;*.bmp;*.tif;*.tiff', 'File Citra (*.png, *.jpg, *.bmp, *.tif)'}, ...
        'Pilih Citra Input', startDir);
    if isequal(fn, 0)
        return;
    end

    fullPath = fullfile(fp, fn);
    try
        setStatus(fig, 'Memuat citra input...', [0.20 0.38 0.62]);
        [rgb, ~] = load_image(fullPath);

        state.currentImagePath = fullPath;
        state.currentImageName = fn;
        state.currentImage     = rgb;

        % Auto-populate Ground Truth field jika mode auto-detect aktif
        autoGt = detectMatchingCamVidGroundTruth(fullPath);
        if get(state.handles.dlChkAutoGT, 'Value') == 1
            set(state.handles.dlEditGT, 'String', autoGt);
        end

        [H, W, C] = size(rgb);
        set(state.handles.lblImageName, 'String', sprintf('File: %s', fn));
        set(state.handles.lblImageRes,  'String', sprintf('Resolusi: %d x %d (%d kanal, uint8)', W, H, C));

        showImageOnAxes(state.handles.axPreview, rgb, sprintf('Preview: %s', fn));
        showImageOnAxes(state.handles.resultAxes(1), rgb, sprintf('1. Original Image (%dx%d)', W, H));

        setappdata(fig, 'AppState', state);
