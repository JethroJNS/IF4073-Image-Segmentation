function val = parseNumericEdit(editHandle, paramName, minVal, mustBeInt)
    raw = strtrim(get(editHandle, 'String'));
    val = str2double(raw);
    if isempty(raw) || isnan(val) || ~isreal(val) || ~isfinite(val) || val < minVal
        error('gui:invalidParameter', ...
              'Parameter "%s" harus berupa angka >= %g (input: "%s").', paramName, minVal, raw);
    end
    if mustBeInt && (val ~= round(val))
        error('gui:invalidParameter', ...
              'Parameter "%s" harus berupa bilangan bulat >= %d.', paramName, minVal);
    end
end

function gtPath = detectMatchingCamVidGroundTruth(imagePath)
    gtPath = '';
    [imgDir, stem, ~] = fileparts(imagePath);
    [parentDir, splitFolder] = fileparts(imgDir);
    cand1 = fullfile(parentDir, [splitFolder '_labels'], [stem '_L.png']);
    cand2 = fullfile(imgDir, [stem '_L.png']);
    if exist(cand1, 'file') == 2
        gtPath = cand1;
    elseif exist(cand2, 'file') == 2
        gtPath = cand2;
    end
end

function s = logicalToStr(tf)
