function fig = launch_segmentation_gui(mode)
%LAUNCH_SEGMENTATION_GUI Meluncurkan GUI MATLAB terintegrasi untuk Tugas 3 IF4073.
%
%   fig = launch_segmentation_gui()
%   spec = launch_segmentation_gui('inspect')
%
%   Mengintegrasikan tiga metode segmentasi citra dalam satu antarmuka:
%     1. Edge Detection   (edge_segmentation.m)
%     2. Split and Merge  (splitMergeSegmentation.m)
%     3. Deep Learning    (run_deep_learning_segmentation.m -> DeepLabV3 MobileNetV3-Large)
%
%   Menggunakan komponen programmatic GUI standar MATLAB (figure, uipanel,
%   uicontrol, axes, uitable) tanpa ketergantungan pada App Designer (.mlapp).

    if nargin < 1
        mode = 'launch';
    end

    projectRoot = getProjectRoot();
    ensurePathsAdded(projectRoot);

    guiSpec = buildGuiSpecification(projectRoot);
    if ischar(mode) && strcmpi(mode, 'inspect')
        fig = guiSpec;
        return;
    end

    % Buat jendela utama aplikasi dengan ukuran proporsional yang kompak & tidak zoomed
    screenSize = get(0, 'ScreenSize'); % [left bottom width height]
    scrW = screenSize(3);
    scrH = screenSize(4);

    % Dimensi window default yang ideal dan pas di resolusi 1366x768 maupun 1920x1080
    figW = min(1180, round(scrW * 0.82));
    figH = min(720,  round(scrH * 0.80));
    figX = max(15, round((scrW - figW) / 2));
    figY = max(30, round((scrH - figH) / 2));

    fig = figure( ...
        'Name',        'Image Segmentation Application - IF4073', ...
        'NumberTitle', 'off', ...
        'MenuBar',     'none', ...
        'ToolBar',     'figure', ...
        'Color',       [0.95 0.96 0.98], ...
        'Units',       'pixels', ...
        'Position',    [figX figY figW figH]);

    % State aplikasi disimpan pada guidata / appdata
    state = initAppState(projectRoot, guiSpec);

    % Bangun seluruh komponen UI
    handles = createGuiComponents(fig, state);
    state.handles = handles;
    setappdata(fig, 'AppState', state);

    % Inisialisasi tampilan awal
    updateMethodParameterPanel(fig);
    clearResultDisplays(fig);
end

%% ========================================================================
%  1. KONFIGURASI & INISIALISASI STATE
%  ========================================================================

function projectRoot = getProjectRoot()
    here = fileparts(mfilename('fullpath'));
    projectRoot = fileparts(fileparts(here));
end

function ensurePathsAdded(projectRoot)
    subDirs = {'edge_detection', 'split_merge', 'utils', 'gui'};
    for i = 1:numel(subDirs)
        p = fullfile(projectRoot, 'src', subDirs{i});
        if exist(p, 'dir') == 7
            addpath(p);
        end
    end
end

function spec = buildGuiSpecification(projectRoot)
    edgeDefaults = default_edge_params();
    edgeMethods  = edge_method_list();
    smDefaults   = splitMergeParams();

    defaultCkpt = fullfile(projectRoot, 'models', 'camvid11_full_25epochs_best.pth');
    [pyExe, pyOk, pyInfo] = find_python_executable();

    spec = struct( ...
        'title',            'Image Segmentation Application', ...
        'subtitle',         'IF4073 - Image Processing', ...
        'projectRoot',      projectRoot, ...
        'methods',          {{'Edge Detection', 'Split and Merge', 'Deep Learning'}}, ...
        'edgeMethods',      {edgeMethods}, ...
        'edgeDefaults',     edgeDefaults, ...
        'splitMergeDefaults', smDefaults, ...
        'defaultCheckpoint', defaultCkpt, ...
        'defaultPython',    pyExe, ...
        'pythonValid',      pyOk, ...
        'pythonInfo',       pyInfo, ...
        'numResultAxes',    4);
end

function state = initAppState(projectRoot, guiSpec)
    state = struct( ...
        'projectRoot',      projectRoot, ...
        'spec',             guiSpec, ...
        'currentImagePath', '', ...
        'currentImageName', '', ...
        'currentImage',     [], ...
        'activeMethod',     'Edge Detection', ...
        'lastResult',       [], ...
        'lastMethod',       '', ...
        'handles',          struct());
end

