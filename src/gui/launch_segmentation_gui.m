    end
end

function saveSummaryText(filePath, linesCell)
    fid = fopen(filePath, 'w');
    if fid == -1
        return;
    end
    if ischar(linesCell)
        fprintf(fid, '%s\n', linesCell);
    elseif iscell(linesCell)
        for i = 1:numel(linesCell)
            fprintf(fid, '%s\n', char(linesCell{i}));
        end
    end
    fclose(fid);
end
