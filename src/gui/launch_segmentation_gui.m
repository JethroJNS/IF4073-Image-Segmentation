function onRunSegmentation(fig)
    state = getappdata(fig, 'AppState');
    if isempty(state.currentImage)
        warndlg('Silakan pilih citra input terlebih dahulu melalui tombol "Browse Image...".', ...
                'Citra Belum Dipilih');
        return;
    end

    method = state.activeMethod;
    setControlsEnabled(state.handles, 'off');
    set(fig, 'Pointer', 'watch');
    setStatus(fig, sprintf('Sedang menjalankan %s... Mohon tunggu.', method), [0.65 0.42 0.05]);
    drawnow;

    try
        switch method
            case 'Edge Detection'
                state = executeEdgeDetection(fig, state);
            case 'Split and Merge'
                state = executeSplitAndMerge(fig, state);
            case 'Deep Learning'
                state = executeDeepLearning(fig, state);
            otherwise
                error('gui:unknownMethod', 'Metode tidak dikenal: %s', method);
        end

        % Periksa apakah GUI masih ada sebelum memperbarui state
        if ~ishandle(fig)
            return;
        end
        setappdata(fig, 'AppState', state);
    catch err
        if ishandle(fig)
            setStatus(fig, sprintf('Error pada %s: %s', method, err.message), [0.70 0.15 0.15]);
            errordlg(sprintf('Terjadi kesalahan saat menjalankan %s:\n\n%s', method, err.message), ...
                     ['Error ' method]);
        end
    end

    if ishandle(fig)
        set(fig, 'Pointer', 'arrow');
        setControlsEnabled(state.handles, 'on');
        drawnow;
    end
end

% -------------------------------------------------------------------------
% 4A. Eksekusi Edge Detection
% -------------------------------------------------------------------------
function state = executeEdgeDetection(fig, state)
    h = state.handles;
    ops = get(h.edgePopupOperator, 'String');
    opName = ops{get(h.edgePopupOperator, 'Value')};

    smoothSigmaVal = parseNumericEdit(h.edgeEditSmoothSigma, 'Smooth Sigma', 0, false);
    zcRatioVal     = parseNumericEdit(h.edgeEditZcRatio,     'Zero-Crossing Ratio', 0, false);

    userParams = struct( ...
        'smoothSigma',       smoothSigmaVal, ...
        'cannySigma',        smoothSigmaVal, ...
        'laplaceSigma',      smoothSigmaVal, ...
        'sensitivity',       parseNumericEdit(h.edgeEditSensitivity, 'Sensitivity', 0.01, false), ...
        'logSigma',          parseNumericEdit(h.edgeEditLogSigma,    'LoG Sigma', 0.1, false), ...
        'zcRatio',           zcRatioVal, ...
        'laplaceRatio',      zcRatioVal, ...
        'numObjects',        parseNumericEdit(h.edgeEditNumObjects,  'Jumlah Objek', 1, true), ...
        'fillBorderObjects', logical(get(h.edgeChkFillBorder, 'Value')));

    params = default_edge_params(userParams);

    % Gunakan matriks RGB uint8 yang sudah dimuat satu kali
    tStart = tic;
    res = edge_segmentation(state.currentImage, opName, params);
    elapsedSec = toc(tStart);
    res.elapsedSeconds = elapsedSec;

    edgeRgb = repmat(uint8(res.edges) * 255, [1 1 3]);

    showImageOnAxes(h.resultAxes(1), res.original,  '1. Original Image');
    showImageOnAxes(h.resultAxes(2), edgeRgb,       sprintf('2. Edge Map (%s)', res.method));
    showImageOnAxes(h.resultAxes(3), res.overlay,   '3. Segmentation Contour Overlay');
    showImageOnAxes(h.resultAxes(4), res.segmented, '4. Segmented Object');

    nEdges = nnz(res.edges);
    totalPx = numel(res.edges);
    edgePct = 100.0 * nEdges / max(totalPx, 1);
    objPct  = 100.0 * res.areaFrac;
    thrVal  = NaN;
    if isfield(res.info, 'threshold')
        thrVal = res.info.threshold;
    end

    summaryLines = { ...
        '=== HASIL SEGMENTASI: EDGE DETECTION ===', ...
        sprintf('Citra           : %s (%dx%d)', state.currentImageName, size(res.original, 2), size(res.original, 1)), ...
        sprintf('Operator        : %s', res.method), ...
        sprintf('Waktu Eksekusi  : %.3f detik (%.1f ms)', elapsedSec, elapsedSec * 1000), ...
        sprintf('Piksel Tepi     : %d px (%.2f%%)', nEdges, edgePct), ...
        sprintf('Luas Objek Mask : %.2f%% (Radius tutup = %d)', objPct, res.radius), ...
        sprintf('Kandidat Objek  : %d (Dipertahankan = %d)', res.numCandidates, params.numObjects), ...
        sprintf('Status Validasi : success=%d, valid=%d', res.success, res.valid)};
    set(h.txtSummaryMetrics, 'String', summaryLines);

    tableData = { ...
        'Operator',             res.method,                              'Deteksi tepi'; ...
        'Waktu Eksekusi',       sprintf('%.4f detik', elapsedSec),       sprintf('%.1f ms', elapsedSec * 1000); ...
        'Smooth Sigma',         sprintf('%.2f', params.smoothSigma),     'Gaussian smoothing'; ...
        'Sensitivity / Ambang', sprintf('%.2f (T=%.4g)', params.sensitivity, thrVal), 'Ambang gradien / ZC'; ...
        'Piksel Tepi',          sprintf('%d px', nEdges),                sprintf('%.2f%% dari citra', edgePct); ...
        'Luas Objek Tersegmentasi', sprintf('%.2f%%', objPct),           sprintf('Radius morfologi = %d', res.radius); ...
        'Fill Border Objects',   logicalToStr(params.fillBorderObjects),  sprintf('Num objects = %d', params.numObjects)};
    set(h.tblStats, ...
        'ColumnName', {'Parameter / Metrik', 'Nilai', 'Keterangan'}, ...
        'Data',       tableData);

    state.lastResult = res;
    state.lastMethod = 'Edge Detection';
    setStatus(fig, sprintf('Edge Detection (%s) selesai dalam %.3f detik.', res.method, elapsedSec), [0.16 0.42 0.24]);
end

% -------------------------------------------------------------------------
% 4B. Eksekusi Split and Merge
% -------------------------------------------------------------------------
function state = executeSplitAndMerge(fig, state)
    h = state.handles;
    critList = get(h.smPopupCriterion, 'String');
    crit = critList{get(h.smPopupCriterion, 'Value')};

    colorModes = get(h.smPopupColorMode, 'String');
    cMode = colorModes{get(h.smPopupColorMode, 'Value')};

    splitThr  = parseNumericEdit(h.smEditSplitThr,  'Split Threshold', 0, false);
    mergeThr  = parseNumericEdit(h.smEditMergeThr,  'Merge Threshold', 0, false);
    minBlock  = parseNumericEdit(h.smEditMinBlock,  'Min Block Size',  1, true);
    minRegion = parseNumericEdit(h.smEditMinRegion, 'Min Region Size', 0, true);
    maxDim    = parseNumericEdit(h.smEditMaxDim,    'Max Dimension',   0, true);

    params = splitMergeParams( ...
        'SplitCriterion', crit, ...
        'SplitThreshold', splitThr, ...
        'MergeThreshold', mergeThr, ...
        'MinBlockSize',   minBlock, ...
        'MinRegionSize',  minRegion, ...
        'ColorMode',      cMode);

    imgInput = state.currentImage;
    subsampleFactor = 1;
    if maxDim > 0
        subsampleFactor = ceil(max(size(imgInput, 1), size(imgInput, 2)) / maxDim);
        if subsampleFactor > 1
            imgInput = imgInput(1:subsampleFactor:end, 1:subsampleFactor:end, :);
        end
    end

    [labels, segmented, info] = splitMergeSegmentation(imgInput, params);

    if size(segmented, 3) == 1
        segDisplay = cat(3, segmented, segmented, segmented);
    else
        segDisplay = segmented;
    end

    splitBoundaryOverlay = overlayBoundaries(imgInput, labelBoundaries(info.splitLabels), [255 255 0]);
    finalLabelsColor     = colorizeLabels(labels);
    finalBoundaryOverlay = overlayBoundaries(imgInput, labelBoundaries(labels), [255 0 0]);

    showImageOnAxes(h.resultAxes(1), imgInput,             sprintf('1. Original Image (%dx%d)', size(imgInput, 2), size(imgInput, 1)));
    showImageOnAxes(h.resultAxes(2), splitBoundaryOverlay, sprintf('2. Split Boundaries (%d blok quadtree)', info.numRegionsSplit));
    showImageOnAxes(h.resultAxes(3), finalLabelsColor,     sprintf('3. Final Region Labels (%d region)', info.numRegionsMerged));
    showImageOnAxes(h.resultAxes(4), segDisplay,           '4. Segmented Image (Region Mean)');

    summaryLines = { ...
        '=== HASIL SEGMENTASI: SPLIT AND MERGE ===', ...
        sprintf('Citra              : %s (%dx%d)', state.currentImageName, size(imgInput, 2), size(imgInput, 1)), ...
        sprintf('Subsample Factor   : %dx', subsampleFactor), ...
        sprintf('Waktu Eksekusi     : %.3f detik', info.elapsedSeconds), ...
        sprintf('Blok Hasil Split   : %d blok quadtree', info.numRegionsSplit), ...
        sprintf('Region Akhir Merge : %d region terhubung', info.numRegionsMerged), ...
        sprintf('Kriteria / Mode    : %s (SplitThr=%g, MergeThr=%g, %s)', ...
                params.SplitCriterion, params.SplitThreshold, params.MergeThreshold, params.ColorMode)};
    set(h.txtSummaryMetrics, 'String', summaryLines);

    tableData = { ...
        'Split Criterion',       params.SplitCriterion,                   'Predikat homogenitas quadtree'; ...
        'Split Threshold',       sprintf('%g', params.SplitThreshold),    sprintf('MinBlockSize = %d px', params.MinBlockSize); ...
        'Merge Threshold',       sprintf('%g', params.MergeThreshold),    sprintf('MinRegionSize = %d px', params.MinRegionSize); ...
        'Color Mode',            params.ColorMode,                        sprintf('ColorSpace = %s', params.ColorSpace); ...
        'Region Setelah Split',  sprintf('%d blok', info.numRegionsSplit), 'Fase 1: Quadtree Decomposition'; ...
        'Region Setelah Merge',  sprintf('%d region', info.numRegionsMerged), 'Fase 2: Region Adjacency Merge'; ...
        'Waktu Eksekusi',        sprintf('%.3f detik', info.elapsedSeconds), sprintf('Resolusi proses %dx%d', size(imgInput, 2), size(imgInput, 1))};
    set(h.tblStats, ...
        'ColumnName', {'Parameter / Metrik', 'Nilai', 'Keterangan'}, ...
        'Data',       tableData);

    state.lastResult = struct( ...
        'original',             imgInput, ...
        'splitBoundaryOverlay', splitBoundaryOverlay, ...
        'finalLabelsColor',     finalLabelsColor, ...
        'finalBoundaryOverlay', finalBoundaryOverlay, ...
        'segmented',            segDisplay, ...
        'labels',               labels, ...
        'info',                 info);
    state.lastMethod = 'Split and Merge';
    setStatus(fig, sprintf('Split and Merge selesai dalam %.2f detik (%d -> %d region).', ...
              info.elapsedSeconds, info.numRegionsSplit, info.numRegionsMerged), [0.16 0.42 0.24]);
end

% -------------------------------------------------------------------------
% 4C. Eksekusi Deep Learning (CamVid 11-Class Semantic Segmentation)
% -------------------------------------------------------------------------
function state = executeDeepLearning(fig, state)
    h = state.handles;
    ckptPath = strtrim(get(h.dlEditCheckpoint, 'String'));
    pyExe    = strtrim(get(h.dlEditPython, 'String'));
    gtPath   = strtrim(get(h.dlEditGT, 'String'));
    if isempty(gtPath) && get(h.dlChkAutoGT, 'Value') == 1
        gtPath = 'auto';
    end

    devList  = get(h.dlPopupDevice, 'String');
    deviceStr = devList{get(h.dlPopupDevice, 'Value')};

    dlOpts = struct( ...
        'CheckpointPath',   ckptPath, ...
        'GroundTruthPath',  gtPath, ...
        'Device',           deviceStr, ...
        'PythonExecutable', pyExe);

    % Gunakan path citra asli jika ada, atau matriks RGB uint8 jika in-memory
    if ~isempty(state.currentImagePath) && exist(state.currentImagePath, 'file') == 2
        dlInput = state.currentImagePath;
    else
        dlInput = state.currentImage;
    end

    res = run_deep_learning_segmentation(dlInput, dlOpts);

    % Panel 1: Citra Asli
    showImageOnAxes(h.resultAxes(1), res.original, '1. Original Image');

    % Panel 2: Ground Truth (jika tersedia) ATAU Distribusi & Legenda 11 Kelas Prediksi
    if res.hasGroundTruth && ~isempty(res.groundTruth)
        showImageOnAxes(h.resultAxes(2), res.groundTruth, ...
            sprintf('2. Ground Truth (11 Classes | Void: %.1f%%)', res.metrics.ignoredPercent));
    else
        renderClassDistributionChartOnAxes(h.resultAxes(2), res.classTable);
    end

    % Panel 3: Predicted Segmentation (11 Classes)
    showImageOnAxes(h.resultAxes(3), res.predictedColor, ...
        sprintf('3. Predicted Segmentation (%d/11 kelas aktif)', nnz([res.classTable.present])));

    % Panel 4: Prediction Overlay pada Citra Asli
    showImageOnAxes(h.resultAxes(4), res.overlay, '4. Prediction Overlay (Alpha 45%)');

    % Ringkasan teks metrik
    if res.hasGroundTruth && isfield(res.metrics, 'pixelAccuracyPercent')
        gtLine1 = sprintf('Pixel Accuracy  : %.2f%% (excl. Void=255)', res.metrics.pixelAccuracyPercent);
        gtLine2 = sprintf('Mean IoU (mIoU) : %.2f%% (%d kelas aktif)', res.metrics.miouPercent, res.metrics.numValidClasses);
    else
        gtLine1 = 'Ground Truth    : Tidak tersedia (Mode Inferensi Murni)';
        gtLine2 = 'Evaluasi IoU    : -';
    end

    summaryLines = { ...
        '=== HASIL SEGMENTASI: DEEP LEARNING (11 KELAS) ===', ...
        sprintf('Citra           : %s (%dx%d)', state.currentImageName, size(res.original, 2), size(res.original, 1)), ...
        sprintf('Model           : DeepLabV3 MobileNetV3-Large'), ...
        sprintf('Device          : %s (Python %s)', res.device, res.pythonInfo.pythonVersion), ...
        sprintf('Waktu Inferensi : %.3f detik (Total: %.2f dtk)', res.inferenceTime, res.totalTime), ...
        gtLine1, ...
        gtLine2};
    set(h.txtSummaryMetrics, 'String', summaryLines);

    % Isi tabel 11 kelas menggunakan nama & warna RGB langsung dari konfigurasi Deep Learning
    nCls = numel(res.classTable);
    tableData = cell(nCls, 6);
    for i = 1:nCls
        ct = res.classTable(i);
        rgbStr = sprintf('(%3d, %3d, %3d)', ct.rgb(1), ct.rgb(2), ct.rgb(3));
        if isnan(ct.iouPercent)
            iouStr = '-';
        else
            iouStr = sprintf('%.2f%%', ct.iouPercent);
        end
        tableData{i, 1} = sprintf('[%2d] %s', ct.classId, ct.className);
        tableData{i, 2} = rgbStr;
        tableData{i, 3} = sprintf('%d px', ct.pixelCount);
        tableData{i, 4} = sprintf('%.2f%%', ct.percentage);
        tableData{i, 5} = logicalToStr(ct.present);
        tableData{i, 6} = iouStr;
    end
    set(h.tblStats, ...
        'ColumnName', {'Kelas (ID 0-10)', 'Palet RGB', 'Piksel Prediksi', 'Proporsi (%)', 'Terdeteksi', 'IoU vs GT'}, ...
        'Data',       tableData);

    state.lastResult = res;
    state.lastMethod = 'Deep Learning';
    if res.hasGroundTruth && isfield(res.metrics, 'miouPercent')
        setStatus(fig, sprintf('Deep Learning selesai (%.2f dtk) | Pixel Acc: %.2f%% | mIoU: %.2f%%.', ...
                  res.inferenceTime, res.metrics.pixelAccuracyPercent, res.metrics.miouPercent), [0.16 0.42 0.24]);
    else
        setStatus(fig, sprintf('Deep Learning selesai dalam %.2f detik (%d/11 kelas terdeteksi).', ...
                  res.inferenceTime, nnz([res.classTable.present])), [0.16 0.42 0.24]);
    end
end

%% ========================================================================
%  5. PENYIMPANAN HASIL (SAVE RESULTS)
%  ========================================================================

function onSaveResults(fig)
    state = getappdata(fig, 'AppState');
    if isempty(state.lastResult) || isempty(state.lastMethod)
        warndlg('Belum ada hasil segmentasi untuk disimpan. Klik "Run Segmentation" terlebih dahulu.', ...
                'Belum Ada Hasil');
        return;
    end

    defaultSaveRoot = fullfile(state.projectRoot, 'results');
    if exist(defaultSaveRoot, 'dir') ~= 7
        mkdir(defaultSaveRoot);
    end

    chosenDir = uigetdir(defaultSaveRoot, 'Pilih Folder Tujuan Penyimpanan Hasil Segmentasi');
    if isequal(chosenDir, 0)
        return;
    end

    try
        [~, stem, ~] = fileparts(state.currentImageName);
        if isempty(stem)
            stem = 'segmented_image';
        end
        r = state.lastResult;

        switch state.lastMethod
            case 'Edge Detection'
                prefix = fullfile(chosenDir, sprintf('%s_edge_%s', stem, lower(r.method)));
                imwrite(r.original,                [prefix '_original.png']);
                imwrite(uint8(r.edges) * 255,      [prefix '_edges.png']);
                imwrite(r.overlay,                 [prefix '_overlay.png']);
                imwrite(r.segmented,               [prefix '_segmented.png']);
                saveSummaryText([prefix '_metadata.txt'], get(state.handles.txtSummaryMetrics, 'String'));

            case 'Split and Merge'
                prefix = fullfile(chosenDir, sprintf('%s_split_merge', stem));
                imwrite(r.original,             [prefix '_original.png']);
                imwrite(r.splitBoundaryOverlay, [prefix '_split_quadtree.png']);
                imwrite(r.finalLabelsColor,     [prefix '_region_labels.png']);
                imwrite(r.finalBoundaryOverlay, [prefix '_region_boundaries.png']);
                imwrite(r.segmented,            [prefix '_segmented.png']);
                saveSummaryText([prefix '_metadata.txt'], get(state.handles.txtSummaryMetrics, 'String'));

            case 'Deep Learning'
                prefix = fullfile(chosenDir, sprintf('%s_deeplabv3_camvid11', stem));
                imwrite(r.original,       [prefix '_original.png']);
                imwrite(r.predicted,      [prefix '_pred_mask.png']);
                imwrite(r.predictedColor, [prefix '_pred_color.png']);
                imwrite(r.overlay,        [prefix '_pred_overlay.png']);
                if r.hasGroundTruth && ~isempty(r.groundTruth)
                    imwrite(r.groundTruth, [prefix '_ground_truth_color.png']);
                end
                srcJson = fullfile(r.outputDir, 'result.json');
                if exist(srcJson, 'file') == 2
                    copyfile(srcJson, [prefix '_result.json']);
                end
                saveSummaryText([prefix '_metadata.txt'], get(state.handles.txtSummaryMetrics, 'String'));
        end

        setStatus(fig, sprintf('Hasil %s berhasil disimpan ke: %s', state.lastMethod, chosenDir), [0.16 0.42 0.24]);
        msgbox(sprintf('Hasil segmentasi (%s) berhasil disimpan ke:\n%s', state.lastMethod, chosenDir), ...
               'Penyimpanan Berhasil');
    catch err
        setStatus(fig, ['Gagal menyimpan hasil: ' err.message], [0.70 0.15 0.15]);
        errordlg(sprintf('Gagal menyimpan hasil segmentasi:\n%s', err.message), 'Error Simpan Hasil');
    end
end

