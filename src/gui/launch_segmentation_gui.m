%  6. FUNGSI HELPER VISUALISASI & VALIDASI
%  ========================================================================

function showImageOnAxes(ax, img, titleStr)
    cla(ax, 'reset');
    if size(img, 3) == 1
        img = repmat(uint8(img), [1 1 3]);
    end
    image(ax, img);
    axis(ax, 'image', 'off');
    tObj = title(ax, titleStr, 'FontSize', 9.5, 'FontWeight', 'bold', 'Interpreter', 'none');
    set(tObj, 'Visible', 'on');
end

function renderClassDistributionChartOnAxes(ax, classTable)
    % Menampilkan grafik distribusi 11 kelas menggunakan palet RGB resmi dari classTable
    cla(ax, 'reset');
    n = numel(classTable);
    pcts = zeros(n, 1);
    names = cell(n, 1);
    for i = 1:n
        pcts(i)  = classTable(i).percentage;
        names{i} = sprintf('[%d] %s (%.1f%%)', classTable(i).classId, classTable(i).className, pcts(i));
    end

    hold(ax, 'on');
    for i = 1:n
        cRgb = classTable(i).rgb / 255.0;
        barh(ax, i, pcts(i), 0.72, 'FaceColor', cRgb, 'EdgeColor', [0.2 0.2 0.2]);
    end
    hold(ax, 'off');

    set(ax, ...
